/** อธิบายค่าเทียบเส้นอ้างอิง WHO แบบไม่ตัดสินผ่าน/ตก (เช่น "สูงกว่าค่าอ้างอิง WHO 3.3 เท่า") */
export const describeVsWhoReference = (value, reference) => {
  if (value == null || !reference) return '—';
  if (value >= reference) {
    const times = value / reference;
    const shown = times >= 10 ? Math.round(times) : times.toFixed(1);
    return `สูงกว่าค่าอ้างอิง WHO ${shown} เท่า`;
  }
  return `ต่ำกว่าค่าอ้างอิง WHO (${(reference - value).toFixed(1)} m²/คน)`;
};
